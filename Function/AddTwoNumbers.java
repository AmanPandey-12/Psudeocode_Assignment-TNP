// Question 32: Add Two Numbers
//
// Pseudocode:
// FUNCTION add(a, b)
//     RETURN a + b
// END FUNCTION

public class AddTwoNumbers {
    static int add(int a, int b) {
        return a + b;
    }

    public static void main(String[] args) {
        System.out.println("Result: " + add(5, 7));
    }
}
