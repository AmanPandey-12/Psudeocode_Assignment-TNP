// Question 33: Cube of a Number
//
// Pseudocode:
// FUNCTION cube(a)
//     RETURN a * a * a
// END FUNCTION

public class CubeOfNumber {
    static int cube(int a) {
        return a * a * a;
    }

    public static void main(String[] args) {
        System.out.println("Cube: " + cube(3));
    }
}
