// Question 35: Area of Triangle
//
// Pseudocode:
// FUNCTION areaTriangle(a, b)
//     RETURN 0.5 * a * b
// END FUNCTION

public class AreaOfTriangle {
    static double areaTriangle(int a, int b) {
        return 0.5 * a * b;
    }

    public static void main(String[] args) {
        System.out.println("Area: " + areaTriangle(10, 5));
    }
}
