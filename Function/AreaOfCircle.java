// Question 34: Area of Circle
//
// Pseudocode:
// FUNCTION areaCircle(r)
//     RETURN 3.14 * r * r
// END FUNCTION

public class AreaOfCircle {
    static double areaCircle(double r) {
        return 3.14 * r * r;
    }

    public static void main(String[] args) {
        System.out.println("Area: " + areaCircle(5.0));
    }
}
