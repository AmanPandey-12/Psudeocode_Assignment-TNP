// Question 7: Print Numbers 10 to 1 (Reverse Order)
//
// Pseudocode:
// BEGIN
//  FOR i = 10 TO 1 STEP -1
//  PRINT i
//  END FOR
// END

public class ReversePrint {
    public static void main(String[] args) {
        for (int i = 10; i >= 1; i--) {
            System.out.println(i);
        }
    }
}
