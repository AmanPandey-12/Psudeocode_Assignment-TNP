// Question 9: While Loop \u2013 Print 1 to 10
//
// Pseudocode:
// BEGIN
//  SET i = 1
//  WHILE i <= 10
//  PRINT i
//  i = i + 1
//  END WHILE
// END

public class WhileExample {
    public static void main(String[] args) {
        int i = 1;
        while (i <= 10) {
            System.out.println(i);
            i++;
        }
    }
}
