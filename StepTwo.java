// Question 14: Print Numbers from 1 to 10 (Step 2)
//
// Pseudocode:
// BEGIN
//  FOR i = 1 TO 10 STEP 2
//  PRINT i
//  END FOR
// END

public class StepTwo {
    public static void main(String[] args) {
        for (int i = 1; i <= 10; i += 2) {
            System.out.println(i);
        }
    }
}
